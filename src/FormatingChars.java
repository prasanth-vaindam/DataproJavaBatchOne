
public class FormatingChars {

	public static void main(String[] args) {
		System.out.println("Student Details");
		System.out.println("Name\t\t: Ravi\n\n");
		System.out.println("Age\t: 20");
		System.out.println("Course\t: Java\n");
		System.out.println("Message: \"Welcome to Java Programming\"");
		System.out.println("C:\\Program Files\\Java");
		System.out.println("Helloo\b");

	}

}
